#!/usr/bin/env python3
"""Generate apple/docs/FEATURE_COVERAGE.md: how the iOS app reaches each command. Called by feature-coverage.sh."""
import os
import re
import subprocess
import sys

apple = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
mode, engine_tsv = sys.argv[1:3]
doc_path = os.path.join(apple, "docs", "FEATURE_COVERAGE.md")


def rows(path, n):
    out = []
    for line in open(path, encoding="utf-8").read().splitlines():
        p = line.split("\t")
        p += [""] * (n - len(p))
        out.append(p[:n])
    return out


engine = rows(engine_tsv, 4)  # id label menu params

excluded = {}
for line in open(os.path.join(apple, "bridge", "ios-excluded-commands.txt"), encoding="utf-8"):
    line = line.rstrip("\n")
    if line.strip() and not line.startswith("#"):
        i, _, why = line.partition("\t")
        excluded[i.strip()] = why.strip()

# ids referenced literally by Swift
swift_ids = set()
src = os.path.join(apple, "FigCraft")
for root, _, files in os.walk(src):
    for f in sorted(files):
        if f.endswith(".swift"):
            text = open(os.path.join(root, f), encoding="utf-8", errors="replace").read()
            for m in re.finditer(r'"(?:command\.)?([A-Za-z]+(?:\.[A-Za-z0-9]+)+)"', text):
                swift_ids.add(m.group(1))

tool_map = {}
tm = os.path.join(apple, "docs", "tool-map.toml")
if os.path.exists(tm):
    cur = None
    for line in open(tm, encoding="utf-8"):
        m = re.match(r"\[([A-Za-z0-9_.]+)\]", line)
        if m:
            cur = m.group(1)
        m = re.match(r'(ios|excluded)\s*=\s*"(.*)"\s*$', line)
        if m and cur:
            tool_map[cur] = (m.group(1), m.group(2))


def status(i, has_menu, is_ui):
    if i in excluded:
        return "excluded", excluded[i]
    sw = i in swift_ids
    if sw and has_menu:
        return "swift+menu", "Swift references it; also in the generated menus"
    if sw:
        return "swift", "referenced by Swift"
    if has_menu:
        return "menu", "generated menu / command palette"
    return ("not reached", "UI-only desktop command with no iOS equivalent yet") if is_ui else ("palette", "command palette only")


lines = []
w = lines.append
w("# Feature coverage")
w("")
w("Generated by `apple/scripts/feature-coverage.sh` (do not edit). How the iOS app reaches each engine command that has")
w("a place in the desktop menus: `swift+menu` / `swift` = referenced by the Swift sources, `menu` = the generated menus")
w("and command palette (which cover every engine catalog command), `excluded` = cannot work on iOS")
w("(`bridge/ios-excluded-commands.txt`). Desktop tools and panels are mapped in `docs/tool-map.toml`.")
w("")
cols = ["swift+menu", "swift", "menu", "excluded"]
tot = {}
eng = sorted((r[0], r[1], r[2]) for r in engine if r[2])
buf = []
for i, label, menu in eng:
    s_, why = status(i, True, False)
    tot[s_] = tot.get(s_, 0) + 1
    buf.append(f"| `{i}` | {label} | {menu.replace('>', ' > ')} | {s_} | {why} |")
w("## Totals")
w("")
w("| Group | Total | " + " | ".join(cols) + " |")
w("|---|---|" + "---|" * len(cols))
w(f"| Engine commands with a menu path | {len(eng)} | " + " | ".join(str(tot.get(k, 0)) for k in cols) + " |")
w("")
w(f"Engine commands in total: {len(engine)}; without a menu path (palette and Swift only): {len(engine) - len(eng)}.")
w("")
w("## Engine commands with a menu path")
w("")
w("| Id | Label | Menu | Status | Note |")
w("|---|---|---|---|---|")
lines.extend(buf)
w("")
w("## Tools and panels")
w("")
w("| Desktop id | iOS |")
w("|---|---|")
for i in sorted(tool_map):
    k, t = tool_map[i]
    w(f"| `{i}` | " + (f"excluded: {t}" if k == "excluded" else t) + " |")
w("")
out = "\n".join(lines)

if mode == "report":
    open(doc_path, "w", encoding="utf-8").write(out)
    print(f"wrote {doc_path}")
else:
    cur = open(doc_path, encoding="utf-8").read() if os.path.exists(doc_path) else ""
    if cur != out:
        print("error: apple/docs/FEATURE_COVERAGE.md is stale: run apple/scripts/feature-coverage.sh", file=sys.stderr)
        sys.exit(1)
    print("feature-coverage: up to date")
